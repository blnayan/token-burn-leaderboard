#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cliPackagePath = path.join(repoRoot, "packages/cli/package.json");
const outputPath = path.join(repoRoot, "apps/web/src/generated/required-cli-version.ts");

const cliPackageJson = JSON.parse(await readFile(cliPackagePath, "utf8"));
const version = cliPackageJson.version;

if (typeof version !== "string" || !version) {
  throw new Error("Unable to determine CLI version from packages/cli/package.json.");
}

const contents = `// This file is generated by scripts/generate-required-cli-version.mjs.
// Do not edit by hand. Update packages/cli/package.json and rerun the generator.

export const requiredCliVersion = ${JSON.stringify(version)};
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, contents);

console.log(
  `Generated ${path.relative(repoRoot, outputPath)} from packages/cli/package.json (${version}).`,
);
